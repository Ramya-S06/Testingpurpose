// +=			-		Addition Assignment
// Example:
// x=10
// x+=100
// =>110
 
// or
 
// x=x+100
// =>110
 
// -=		-		subtraction assignment
// x=10
// x-=5
// =>5
 
// or
 
// x=x-5
// =>5
 
// *=		-		Multiplication Assignment
// x=10
// x*=5;
// =>50
 
// or
 
// x=x*5
// =>50
 
// /=			-		Division Assignment
// x=25
// x/=5
// =>5
 
// or
// x=x/5
// =>5
 
// %=			-		Modulus Assignment
// x=10
// x%=3
// =>1
 
// or
// x=x%3
// =>1