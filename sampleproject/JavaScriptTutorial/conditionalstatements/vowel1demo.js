let ch='o'
 
switch(ch){
    case 'A':case 'E':case 'I':case 'O':case 'U'://uppercase
        console.log(ch+" is a Vowel");
        break
    case 'a':case 'e':case 'i':case 'o':case 'u'://lowercase
        console.log(ch+" is a Vowel");
        break
    default:
        console.log(ch+" is not a Vowel");
       
}